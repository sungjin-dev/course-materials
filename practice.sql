SELECT *
 FROM EMP E, DEPT D
 WHERE E.DEPTNO = D.DEPTNO
ORDER BY EMPNO;

SELECT E.EMPNO, E.ENAME, E.SAL, D.DEPTNO, D.DNAME, D.LOC
FROM EMP E, DEPT D
WHERE E.DEPTNO = D.DEPTNO
 AND SAL >= 3000;
 
SELECT EMPNO, ENAME, ROW_NUMBER()OVER (ORDER BY SAL DESC) 
AS RANK FROM EMP;

SELECT EMPNO, ENAME, RANK()OVER(ORDER BY SAL DESC)AS RANK FROM EMP;

SELECT EMPNO, ENAME, DENSE_RANK()OVER(ORDER BY SAL DESC) AS RNAK FROM EMP;

SELECT EMPNO, ENAME, SUM(SAL) OVER (PARTITION BY DEPTNO) FROM EMP;

SELECT EMPNO, ENAME, SAL, 
    NTILE(10)OVER(ORDER BY SAL)AS NT,
    CUME_DIST()OVER(ORDER BY SAL)AS CUM,
    PERCENT_RANK()OVER(ORDER BY SAL)AS PER,
    RATIO_TO_REPORT(SAL)OVER()AS SALING_RATIO FROM EMP;
